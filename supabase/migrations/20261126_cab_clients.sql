-- Личный кабинет v3: карточка клиента в админке (что смотрел / что искал) и подборки менеджера.
-- Выполнить целиком в Supabase → SQL Editor (вставить СОДЕРЖИМОЕ, не имя файла).
-- Профиль клиента, «был в сети» и заметки менеджера лежат в уже существующей alert_meta — отдельных таблиц не нужно.

-- Журнал действий клиента (только после подключения Telegram): открыл лот / искал в каталоге
create table if not exists public.cab_events (
  id      bigint generated by default as identity primary key,
  chat_id bigint not null,
  kind    text   not null check (kind in ('view','search','calc','open')),
  key     text   not null,                       -- view: copart-123; search: строка фильтров
  data    jsonb  not null default '{}'::jsonb,
  at      timestamptz not null default now()
);
create index if not exists idx_cab_events_chat      on public.cab_events (chat_id, at desc);
create index if not exists idx_cab_events_chat_key  on public.cab_events (chat_id, kind, key, at desc);
alter table public.cab_events enable row level security;      -- политик нет: доступ только сервисным ключом

-- Подборки менеджера клиенту: лот + комментарий; клиент отмечает «нравится / не подходит / обсудить»
create table if not exists public.cab_picks (
  id            bigint generated by default as identity primary key,
  chat_id       bigint not null,
  lot_id        text   not null,                 -- copart-123 / iaai-456
  data          jsonb  not null default '{}'::jsonb,   -- снимок лота на момент отправки
  note          text,
  created_at    timestamptz not null default now(),
  seen_at       timestamptz,
  reaction      text check (reaction in ('like','no','discuss')),
  reaction_note text,
  reaction_at   timestamptz,
  active        boolean not null default true,
  unique (chat_id, lot_id)
);
create index if not exists idx_cab_picks_chat on public.cab_picks (chat_id, created_at desc);
alter table public.cab_picks enable row level security;

