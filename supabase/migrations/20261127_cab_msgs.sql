-- Переписка с клиентом из админки (27.11.2026): сообщения клиента боту сохраняются, менеджер отвечает из карточки клиента.
-- Выполнять в Supabase SQL Editor целиком одним запросом.

create table if not exists public.cab_msgs (
  id         bigint generated by default as identity primary key,
  chat_id    text        not null,
  dir        text        not null check (dir in ('in','out')),   -- in: от клиента, out: от менеджера
  text       text        not null,
  seen       boolean     not null default false,                 -- для in: менеджер прочитал
  at         timestamptz not null default now()
);
create index if not exists idx_cab_msgs_chat on public.cab_msgs (chat_id, at desc);
create index if not exists idx_cab_msgs_unread on public.cab_msgs (dir, seen) where dir = 'in' and seen = false;

alter table public.cab_msgs enable row level security;   -- политик нет: только сервисный ключ

notify pgrst, 'reload schema';
