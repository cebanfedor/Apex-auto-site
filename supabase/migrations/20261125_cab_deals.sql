-- «Мои сделки» в личном кабинете (25.11.2026): менеджер заводит сделку в админке (вкладка «Сделки»),
-- клиент видит её в кабинете после подтверждения номера телефона через Telegram (кнопка «Поделиться номером»).
-- Выполнять в Supabase SQL Editor целиком одним запросом.

create table if not exists public.cab_deals (
  id             bigint generated by default as identity primary key,
  phone_key      text   not null,                 -- последние 8 цифр телефона клиента (по ним связываем с Telegram)
  phone          text,
  client_name    text,
  title          text   not null,                 -- «2021 BMW X5 xDrive40i»
  vin            text,
  stage          text   not null default 'bought',-- bought|paid|pickup|port|sea|klaipeda|road|customs|ready|done
  next_step      text,                            -- «что дальше» простым языком
  eta_date       date,
  total_usd      numeric,
  paid_usd       numeric,
  timeline       jsonb  not null default '[]'::jsonb,   -- [{at:'2026-11-20', text:'…'}]
  photos         jsonb  not null default '[]'::jsonb,   -- [{url, caption}]
  docs           jsonb  not null default '[]'::jsonb,   -- [{name, url}]
  active         boolean not null default true,
  notified_stage text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists idx_cab_deals_phone on public.cab_deals (phone_key, active, updated_at desc);

alter table public.cab_deals enable row level security;   -- политик нет: только сервисный ключ

